export function translateItemName(name: string, lang: Language): string {
  if (!name || lang === 'id') return name;
  const key = name.toLowerCase().trim();
  if (SPOT_FACILITIES_TRANSLATIONS[key]) {
    return SPOT_FACILITIES_TRANSLATIONS[key].en;
  }
  return name;
}

export function getSpotSurface(facilities?: string[]): string | undefined {
  if (!Array.isArray(facilities)) return undefined;
  return facilities.find((f) => {
    const lower = f.toLowerCase().trim();
    if (lower.includes('tanpa alas')) return false;
    return lower.startsWith('alas ') || lower === 'deck kayu';
  });
}

